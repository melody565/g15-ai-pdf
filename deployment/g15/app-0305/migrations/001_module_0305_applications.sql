CREATE TABLE IF NOT EXISTS module_0305_applications (
    id BIGSERIAL PRIMARY KEY,
    owner_session UUID NOT NULL,
    application_no VARCHAR(32) NOT NULL,
    application_name VARCHAR(120) NOT NULL,
    department VARCHAR(80) NOT NULL,
    owner_name VARCHAR(40) NOT NULL,
    email VARCHAR(254) NOT NULL,
    phone VARCHAR(32) NOT NULL,
    category VARCHAR(80) NOT NULL,
    priority VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    currency VARCHAR(3) NOT NULL,
    budget NUMERIC(14,2) NOT NULL,
    tags JSONB NOT NULL DEFAULT '[]'::jsonb,
    meeting_method VARCHAR(10) NOT NULL,
    meeting_value TEXT NOT NULL,
    discount_percent NUMERIC(5,2) NOT NULL,
    tax_rate SMALLINT NOT NULL,
    billing_type VARCHAR(10) NOT NULL,
    invoice_title VARCHAR(120) NOT NULL DEFAULT '',
    tax_id VARCHAR(8) NOT NULL DEFAULT '',
    details JSONB NOT NULL,
    subtotal NUMERIC(14,2) NOT NULL,
    discount_amount NUMERIC(14,2) NOT NULL,
    tax_amount NUMERIC(14,2) NOT NULL,
    total NUMERIC(14,2) NOT NULL,
    notes VARCHAR(2000) NOT NULL DEFAULT '',
    confirmed BOOLEAN NOT NULL,
    version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT module_0305_owner_number_unique UNIQUE(owner_session, application_no),
    CONSTRAINT module_0305_dates_valid CHECK(end_date >= start_date),
    CONSTRAINT module_0305_budget_valid CHECK(budget BETWEEN 0 AND 10000000),
    CONSTRAINT module_0305_discount_valid CHECK(discount_percent BETWEEN 0 AND 50),
    CONSTRAINT module_0305_tax_valid CHECK(tax_rate IN (0,5,10)),
    CONSTRAINT module_0305_version_valid CHECK(version > 0)
);
CREATE INDEX IF NOT EXISTS module_0305_owner_updated_idx ON module_0305_applications(owner_session, updated_at DESC);
